def parse_item(code, lines):
    """저자 문법 → groups(=Level 4 묶음) 구조."""
    groups = [{"title": None, "code": None, "observations": []}]
    time_d, basis_d = "", ""
    for ln in lines:
        if ln.startswith("#"):
            if groups[-1]["title"] is None and not groups[-1]["observations"]: groups.pop()
            groups.append({"title": ln[1:].strip(), "code": None, "observations": []})
            time_d, basis_d = "", ""
            continue
        if ln.startswith("@"):
            p = (ln[1:] + "|").split("|"); time_d, basis_d = p[0].strip(), p[1].strip(); continue
        f = [x.strip() for x in (ln + "||||||").split("|")[:7]]
        name, typ, unit, axis, time, basis, note = f
        obs = {"name": name, "type": typ, "unit": unit, "axis": axis or "—",
               "time": time or time_d, "basis": basis or basis_d, "note": note}
        groups[-1]["observations"].append(obs)
    for i, g in enumerate(groups, 1):
        g["code"] = "%02d" % i if g["title"] else None
    for g in groups:
        for j, o in enumerate(g["observations"], 1):
            o["id"] = "OBS." + code + ("." + g["code"] if g["code"] else "") + ".%02d" % j
    return groups

def main():
    tree = json.load(open(os.path.join(ROOT, "skeleton", "data_tree_template.json"), encoding="utf-8"))
    nodes = {}
    def walk(n):
        nodes[n["id"]] = n
        for c in n.get("children") or []: walk(c)
    walk(tree["root"])
    # 표 유형 근거(구조 조사 5건): 노드 또는 상위 절에 카탈로그된 표가 있으면 관측 근거로 붙인다
    ev = collections.defaultdict(set)
    sk = os.path.join(ROOT, "dist", "skeleton.json")
    if os.path.exists(sk):
        for t in json.load(open(sk, encoding="utf-8")).get("table_types") or []:
            for r in t["reports"]: ev[t["node"]].add(r)

    items, problems, total = {}, [], 0
    for code, lines in OBS.items():
        nid = "DT.A001." + code
        if nid not in nodes: problems.append(f"트리에 없는 항목 코드: {code}"); continue
        groups = parse_item(code, lines)
        for g in groups:
            for o in g["observations"]:
                for t in o["type"].split("·"):
                    if t and t not in TYPES: problems.append(f"{o['id']} 유형 어휘 아님: {t}")
                if not o["name"]: problems.append(f"{o['id']} 관측명 없음")
                total += 1
        direct = sorted(ev.get(nid, ()))
        parent = nid.rsplit(".", 1)[0]
        inherited = sorted(ev.get(parent, ())) if not direct else []
        items[nid] = {"code": code, "title": nodes[nid]["title"], "level": nodes[nid].get("level"),
                      "scope": nodes[nid].get("scope"), "groups": groups,
                      "observation_count": sum(len(g["observations"]) for g in groups),
                      "subitem_count": sum(1 for g in groups if g["title"]),
                      "evidence_reports": direct or inherited,
                      "evidence_level": "항목" if direct else ("절" if inherited else "없음")}
    leaves = [n for n in nodes.values() if not (n.get("children") or []) and n["id"] != "DT.A001"]
    missing = [n["id"] for n in leaves if n["id"] not in items]
    out = {"meta": {"title": "사업보고서 데이터 트리 관측 카탈로그 v0.1",
                    "item_count": len(items), "observation_count": total,
                    "subitem_count": sum(v["subitem_count"] for v in items.values()),
                    "leaf_nodes": len(leaves), "leaves_without_observations": missing,
                    "basis": "기업공시서식 작성기준(사업보고서) + 구조 조사 5건의 표 머리글 관측",
                    "rule": "한 항목 안에 grain 이 다른 표가 둘 이상이면 Level 4 로 세분화한다. 같은 표 안의 여러 측정치는 관측 여러 건이다."},
           "vocab": {"measure_types": sorted(TYPES),
                     "status": ["실제", "계획", "예정", "잠정", "가정", "승인전", "미산출", "해당없음"],
                     "field_map": {"name": "measure", "unit": "unit", "axis": "dimension/subject_role",
                                   "time": "time", "basis": "scope+basis", "note": "condition"}},
           "items": items}
    p = os.path.join(ROOT, "skeleton", "observations.json")
    json.dump(out, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"항목 {len(items)} · 하위항목(Level 4) {out['meta']['subitem_count']} · 관측 {total}")
    print(f"관측 근거: 항목 단위 {sum(1 for v in items.values() if v['evidence_level']=='항목')} / "
          f"절 단위 {sum(1 for v in items.values() if v['evidence_level']=='절')} / 없음 {sum(1 for v in items.values() if v['evidence_level']=='없음')}")
    if missing: print(f"관측 미작성 말단 노드 {len(missing)}: {missing[:12]}")
    for q in problems[:20]: print("  !", q)
    print("→", p)

if __name__ == "__main__":
    main()
